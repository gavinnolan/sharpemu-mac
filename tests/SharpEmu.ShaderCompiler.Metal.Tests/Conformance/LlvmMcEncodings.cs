using System.Diagnostics;
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.RegularExpressions;

namespace SharpEmu.ShaderCompiler.Metal.Tests.Conformance;

/// <summary>
/// Machine encodings of the conformance programs, produced by LLVM's gfx1030 assembler
/// (<c>llvm-mc -triple=amdgcn -mcpu=gfx1030 -show-encoding</c>) and checked in as
/// <c>Rdna2Encodings.txt</c>, so the encodings come from an assembler that shares nothing
/// with our decoder and the suite needs no LLVM to run. Each line is
/// <c>wave&lt;TAB&gt;assembly&lt;TAB&gt;hex words</c>. Regenerate with
/// <c>SHARPEMU_REGEN_RDNA2_ENCODINGS=/path/to/llvm-mc</c> (see <see cref="Regenerate"/>).
/// </summary>
internal static partial class LlvmMcEncodings
{
    private const string FileName = "Rdna2Encodings.txt";
    private static readonly Lazy<Dictionary<(int Wave, string Asm), uint[]>> Table = new(Load);

    public static string SourcePath([CallerFilePath] string path = "") =>
        Path.Combine(Path.GetDirectoryName(path)!, FileName);

    public static bool TryEncode(int wave, string asm, out uint[] words) =>
        Table.Value.TryGetValue((wave, Normalize(asm)), out words!);

    public static string Normalize(string asm) => MultipleSpaces().Replace(asm.Trim(), " ");

    private static Dictionary<(int, string), uint[]> Load()
    {
        var table = new Dictionary<(int, string), uint[]>();
        var path = Path.Combine(AppContext.BaseDirectory, "Conformance", FileName);
        if (!File.Exists(path)) path = SourcePath();
        if (!File.Exists(path)) return table;
        foreach (var line in File.ReadLines(path))
        {
            if (line.Length == 0 || line[0] == '#') continue;
            var parts = line.Split('\t');
            var words = parts[2].Split(' ', StringSplitOptions.RemoveEmptyEntries)
                .Select(static word => uint.Parse(word, NumberStyles.HexNumber, CultureInfo.InvariantCulture)).ToArray();
            table[(int.Parse(parts[0], CultureInfo.InvariantCulture), parts[1])] = words;
        }

        return table;
    }

    /// <summary>Assembles every (wave, asm) line with llvm-mc and rewrites the checked-in table.
    /// Lines the assembler rejects are reported back rather than written.</summary>
    public static IReadOnlyList<string> Regenerate(string llvmMc, IEnumerable<(int Wave, string Asm)> lines)
    {
        var rejected = new List<string>();
        var output = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var group in lines.Select(static line => (line.Wave, Asm: Normalize(line.Asm))).Distinct().GroupBy(static line => line.Wave))
        {
            var pending = group.Select(static line => line.Asm).ToList();
            while (pending.Count > 0)
            {
                var (encodings, failedLines) = Assemble(llvmMc, group.Key, pending);
                if (failedLines.Count == 0)
                {
                    for (var index = 0; index < pending.Count; index++)
                    {
                        output[$"{group.Key}\t{pending[index]}"] = encodings[index];
                    }

                    break;
                }

                foreach (var failed in failedLines.OrderDescending())
                {
                    rejected.Add($"w{group.Key}: {pending[failed]}");
                    pending.RemoveAt(failed);
                }
            }
        }

        var builder = new StringBuilder();
        builder.Append("# Generated by llvm-mc -triple=amdgcn -mcpu=gfx1030 -show-encoding; see LlvmMcEncodings.cs.\n");
        foreach (var (key, words) in output)
        {
            builder.Append(key).Append('\t').Append(words).Append('\n');
        }

        File.WriteAllText(SourcePath(), builder.ToString());
        return rejected;
    }

    private static (List<string> Encodings, List<int> FailedLines) Assemble(string llvmMc, int wave, List<string> lines)
    {
        var start = new ProcessStartInfo(llvmMc)
        {
            RedirectStandardInput = true,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
        };
        foreach (var argument in (string[])["-triple=amdgcn", "-mcpu=gfx1030", "-show-encoding",
                     wave == 64 ? "-mattr=-wavefrontsize32,+wavefrontsize64" : "-mattr=+wavefrontsize32,-wavefrontsize64"])
        {
            start.ArgumentList.Add(argument);
        }

        using var process = Process.Start(start)!;
        var stdout = process.StandardOutput.ReadToEndAsync();
        var stderr = process.StandardError.ReadToEndAsync();
        process.StandardInput.Write(string.Join('\n', lines) + "\n");
        process.StandardInput.Close();
        process.WaitForExit();
        var failed = ErrorLine().Matches(stderr.Result)
            .Select(static match => int.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture) - 1)
            .Distinct().ToList();
        if (failed.Count > 0) return ([], failed);
        var encodings = new List<string>();
        foreach (Match match in EncodingLine().Matches(stdout.Result))
        {
            var bytes = match.Groups[1].Value.Split(',').Select(static b => Convert.ToByte(b.Trim(), 16)).ToArray();
            var words = new List<string>();
            for (var offset = 0; offset < bytes.Length; offset += 4)
            {
                words.Add(BitConverter.ToUInt32(bytes, offset).ToString("X8", CultureInfo.InvariantCulture));
            }

            encodings.Add(string.Join(' ', words));
        }

        if (encodings.Count != lines.Count)
        {
            throw new InvalidOperationException($"llvm-mc returned {encodings.Count} encodings for {lines.Count} lines:\n{stderr.Result}");
        }

        return (encodings, []);
    }

    [GeneratedRegex(@"<stdin>:(\d+):\d+: error")]
    private static partial Regex ErrorLine();

    [GeneratedRegex(@"encoding: \[([^\]]*)\]")]
    private static partial Regex EncodingLine();

    [GeneratedRegex(@"\s+")]
    private static partial Regex MultipleSpaces();
}
