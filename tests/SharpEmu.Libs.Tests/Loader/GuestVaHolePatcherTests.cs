using SharpEmu.Core.Loader;
using Xunit;

namespace SharpEmu.Libs.Tests.Loader;

// The arena-base loads macOS 27's guard over [0x10_0000_0000, 0x70_0000_0000) makes the loader move:
// RAGE's stored streaming arena base and a base loaded for a one-entry sceKernelBatchMap.
public sealed class GuestVaHolePatcherTests
{
    [Fact]
    public void TheArenaBaseLoadsAreFoundAndOtherLoadsOfTheConstantAreNot()
    {
        byte[] code =
        [
            0x90,
            // RAGE: movabs rax, 0x1000000000; lea rdi, [rip+..]; mov esi, ..; mov rdx, rbx; mov [rip+..], rax
            0x48, 0xB8, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
            0x48, 0x8D, 0x3D, 0x11, 0x22, 0x33, 0x44,
            0xBE, 0x01, 0x02, 0x03, 0x04,
            0x48, 0x89, 0xDA,
            0x48, 0x89, 0x05, 0x55, 0x66, 0x77, 0x00,
            // Ghost of Tsushima: movabs r15, 0x1000000000; lea rdi, [rbp-0x48]; mov esi, 1; xor edx, edx
            0x49, 0xBF, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
            0x48, 0x8D, 0x7D, 0xB8,
            0xBE, 0x01, 0x00, 0x00, 0x00,
            0x31, 0xD2,
            // A range check: movabs rdx, 0x1000000000; cmp rax, rdx; jb
            0x48, 0xBA, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
            0x48, 0x39, 0xD0, 0x72, 0x2C,
            // The batch shape with two entries is not one arena's map.
            0x49, 0xBE, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
            0x48, 0x8D, 0x7D, 0xC0,
            0xBE, 0x02, 0x00, 0x00, 0x00,
            0x31, 0xD2,
        ];

        Assert.Equal([1, 33], GuestVaHolePatcher.FindArenaBaseSites(code));
    }
}
